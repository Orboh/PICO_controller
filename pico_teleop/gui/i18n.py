EMERGENCY_JA = " — 緊急時は非常停止を（このページではない）。"


def t(key: str, lang: str, **kw) -> str:
    en, ja = TEXT.get(key, (key, key))
    s = ja if lang == "ja" else en
    return s.format(**kw) if kw else s


def refusal(msg: str, lang: str) -> str:
    if lang != "ja":
        return msg
    for prefix, ja in REFUSALS_JA:
        if msg.startswith(prefix):
            return ja + (EMERGENCY_JA if "e-stop" in msg else "") + f"（{msg}）"
    return msg
